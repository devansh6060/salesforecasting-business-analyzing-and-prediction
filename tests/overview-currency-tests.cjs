const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<section id="dashboard"><div class="kpis"></div></section>', { runScripts: 'outside-only' });
const w = dom.window;
const requests = [];
let resolveRate;
let renders = 0;
w.ForecastIQCurrency = 'GBP';
w.marketJSON = url => { requests.push(url); return new Promise(resolve => { resolveRate = resolve; }); };
w.render = () => { renders++; w.ForecastIQOverviewCurrency.sync(); };
w.renderBusinessPulse = w.renderScenario = w.renderExecutiveSummary = () => {};
w.eval(fs.readFileSync('overview-currency.js', 'utf8'));
const flush = () => new Promise(resolve => setImmediate(resolve));
async function main() { try {
  const overview = w.ForecastIQOverviewCurrency;
  overview.sync(); overview.sync();
  assert.equal(requests.length, 1, 'Coalesce repeated renders into one exchange-rate request');
  assert.equal(overview.convert(100), null, 'Never label unconverted source amounts as USD');
  resolveRate({ base: 'GBP', quote: 'USD', rate: 1.25, date: '2026-10-30' });
  await flush();
  assert.equal(overview.convert(100), 125);
  assert.equal(w.overviewMoney(100), '$125');
  assert.match(w.document.getElementById('overviewCurrencyNote').textContent, /2026-10-30/);
  assert.equal(w.ForecastIQCurrency, 'GBP', 'Preserve the original source currency');
  w.ForecastIQCurrency = 'INR'; overview.sync();
  const before = renders;
  w.ForecastIQCurrency = 'USD'; overview.sync();
  resolveRate({ base: 'INR', quote: 'USD', rate: 0.012, date: '2026-10-30' });
  await flush();
  assert.equal(renders, before, 'An old currency request must not redraw the newly selected source');
  assert.equal(overview.convert(100), 100);
  w.ForecastIQCurrency = 'EUR';
  w.marketJSON = async () => { throw Error('offline'); };
  overview.sync(); await flush();
  assert.equal(overview.convert(100), null);
  assert.match(w.document.getElementById('overviewCurrencyNote').textContent, /unavailable/);
  w.marketJSON = async () => ({ base: 'EUR', quote: 'USD', rate: 1.1, date: '2026-10-30' });
  w.document.querySelector('button').click(); await flush();
  assert.equal(w.overviewMoney(100), '$110');
  console.log('Overview USD conversion, original data, request coalescing, source changes, failure and retry passed.');
} finally { w.close(); } }
main().catch(error => { console.error(error); process.exitCode = 1; });
